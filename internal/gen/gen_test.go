package gen_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/go-kanna/internal/cli"

	"github.com/go-kanna/i18n/internal/gen"
)

type result struct {
	code        int
	stdout, err string
}

// execute runs kanna-i18n in dir with args.
func execute(t *testing.T, dir string, args ...string) result {
	t.Helper()

	var stdout, stderr strings.Builder
	code := gen.Command().Exec(cli.Env{Out: &stdout, Err: &stderr, Dir: dir}, args)
	return result{code: code, stdout: stdout.String(), err: stderr.String()}
}

func readFile(t *testing.T, path string) string {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(path))
	if err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	return string(data)
}

// locales is a default language and a translation of all of it.
var locales = map[string]string{
	"locales/en.yaml": "greeting: \"Hello!\"\nhello: \"Hello, {name}!\"\n",
	"locales/ja.yaml": "greeting: \"こんにちは！\"\nhello: \"こんにちは、{name}さん！\"\n",
}

func TestCommand(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFiles(t, dir, locales)

	if got := execute(t, dir); got != (result{}) {
		t.Fatalf("Exec() = %+v, want success without a word", got)
	}
	src := readFile(t, filepath.Join(dir, "messages", "i18n_gen.go"))
	for _, want := range []string{
		"// Code generated by kanna-i18n. DO NOT EDIT.\n\npackage messages\n",
		"func Hello(name string) i18n.Message {",
		`i18n.Catalog{Lang: "ja"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("i18n_gen.go does not hold %q:\n%s", want, src)
		}
	}

	if got := execute(t, dir, "-v"); got.stdout != "unchanged messages/i18n_gen.go\n" || got.code != cli.ExitOK {
		t.Errorf("Exec(-v) = %+v, want the file left unchanged", got)
	}
}

func TestCommand_flags(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"i10n/de.yaml": "greeting: \"Hallo!\"\n",
		"i10n/en.yaml": "greeting: \"Hello!\"\n",
	})

	got := execute(t, dir, "-locales", "i10n", "-default", "de", "-destination", "gen", "-package", "msg")
	if got.code != cli.ExitOK {
		t.Fatalf("Exec() = %+v", got)
	}
	src := readFile(t, filepath.Join(dir, "gen", "i18n_gen.go"))
	for _, want := range []string{"package msg\n", "var bundle = i18n.NewBundle(\n\ti18n.Catalog{Lang: \"de\""} {
		if !strings.Contains(src, want) {
			t.Errorf("i18n_gen.go does not hold %q:\n%s", want, src)
		}
	}
}

// The package and the names the destination declares already are kept.
func TestCommand_destinationPackage(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFiles(t, dir, locales)
	writeFiles(t, dir, map[string]string{
		"messages/doc.go": "// Package msgs holds messages.\npackage msgs\n\nvar bundle = 1\n",
	})

	if got := execute(t, dir); got.code != cli.ExitOK {
		t.Fatalf("Exec() = %+v", got)
	}
	src := readFile(t, filepath.Join(dir, "messages", "i18n_gen.go"))
	for _, want := range []string{"package msgs\n", "var bundle2 = "} {
		if !strings.Contains(src, want) {
			t.Errorf("i18n_gen.go does not hold %q:\n%s", want, src)
		}
	}

	got := execute(t, dir, "-package", "other")
	want := "./messages: error: the Go files there declare package msgs, not other\n"
	if got.code != cli.ExitFailure || got.err != want {
		t.Errorf("Exec(-package other) = %+v, want stderr %q", got, want)
	}
}

// The diagnostics are the README's.
func TestCommand_diagnostics(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"locales/en.yaml": enYAML,
		"locales/ja.yaml": "greeting: \"こんにちは！\"\nhello: \"こんにちは、{namae}さん！\"\n" +
			"items_count:\n  plural:\n    other: \"アイテムが{count}個あります。\"\n" +
			"total_price: \"合計: {price:int}\"\nuser:\n  not_fund: \"ユーザーが見つかりません。\"\n",
	})

	got := execute(t, dir)
	want := `locales/ja.yaml:2:8: error: parameter "namae" of key "hello" is not in en
  did you mean "name"?
locales/ja.yaml:6:14: error: parameter "price" of key "total_price" is int, but number in en
locales/ja.yaml:8:3: error: key "user.not_fund" is not in en
  did you mean "user.not_found"?
locales/ja.yaml: warning: missing keys: user.not_found
`
	if got.code != cli.ExitFailure || got.err != want || got.stdout != "" {
		t.Errorf("Exec() = %+v\nwant stderr\n%s", got, want)
	}
	if _, err := os.Stat(filepath.Join(dir, "messages")); !os.IsNotExist(err) {
		t.Errorf("Exec() wrote the destination despite the errors: %v", err)
	}
}

func TestCommand_failures(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		args func(dir string) []string
		want string
	}{
		{
			name: "no locale directory, named by its absolute path",
			args: func(dir string) []string { return []string{"-locales", filepath.Join(dir, "nowhere")} },
			want: "./nowhere: error: cannot read the locale directory: no such file or directory\n" +
				"  -locales names the directory holding the locale files\n",
		},
		{
			name: "no locale file for the default language",
			args: func(string) []string { return []string{"-default", "fr"} },
			want: "./locales: error: no locale file for fr, the default language\n" +
				"  there are locale files for en, ja; choose one with -default\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			writeFiles(t, dir, locales)

			if got := execute(t, dir, tt.args(dir)...); got.code != cli.ExitFailure || got.err != tt.want {
				t.Errorf("Exec() = %+v\nwant stderr\n%s", got, tt.want)
			}
		})
	}
}

func TestCommand_check(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFiles(t, dir, locales)

	if got := execute(t, dir, "-check"); got.code != cli.ExitFailure ||
		got.err != "messages/i18n_gen.go: error: not generated yet; run go generate\n" {
		t.Errorf("Exec(-check) before generating = %+v", got)
	}
	if got := execute(t, dir); got.code != cli.ExitOK {
		t.Fatalf("Exec() = %+v", got)
	}
	if got := execute(t, dir, "-check"); got != (result{}) {
		t.Errorf("Exec(-check) after generating = %+v", got)
	}

	writeFiles(t, dir, map[string]string{"locales/en.yaml": "greeting: \"Hi!\"\nhello: \"Hi, {name}!\"\n"})
	if got := execute(t, dir, "-check"); got.code != cli.ExitFailure ||
		got.err != "messages/i18n_gen.go: error: out of date; run go generate\n" {
		t.Errorf("Exec(-check) after a change = %+v", got)
	}
}

func TestCommand_handWritten(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFiles(t, dir, locales)
	writeFiles(t, dir, map[string]string{"messages/i18n_gen.go": "package messages\n\n// Written by hand.\n"})

	got := execute(t, dir)
	if got.code != cli.ExitFailure || !strings.HasPrefix(got.err, "messages/i18n_gen.go: error: ") {
		t.Errorf("Exec() = %+v, want it refused", got)
	}
	if got := readFile(t, filepath.Join(dir, "messages", "i18n_gen.go")); !strings.Contains(got, "Written by hand.") {
		t.Errorf("the hand-written file was overwritten:\n%s", got)
	}
}

func TestCommand_usage(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		args    []string
		wantErr string // a prefix of stderr
	}{
		{name: "an argument", args: []string{"locales"}, wantErr: "unexpected argument \"locales\"\n"},
		{
			name:    "a default that is no language tag",
			args:    []string{"-default", "not a tag"},
			wantErr: "invalid value \"not a tag\" for flag -default: ",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			writeFiles(t, dir, locales)

			got := execute(t, dir, tt.args...)
			if got.code != cli.ExitUsage || !strings.HasPrefix(got.err, tt.wantErr) || !strings.Contains(got.err, "Usage:") {
				t.Errorf("Exec(%q) = %+v, want a usage error starting %q", tt.args, got, tt.wantErr)
			}
			if _, err := os.Stat(filepath.Join(dir, "messages")); !os.IsNotExist(err) {
				t.Errorf("Exec(%q) wrote the destination", tt.args)
			}
		})
	}
}

// Without the runtime in go.mod, the generated package would not build; the
// run says so instead of the build after it.
func TestCommand_missingRequire(t *testing.T) {
	t.Setenv("GOWORK", "off")

	dir := t.TempDir()
	writeFiles(t, dir, locales)
	writeFiles(t, dir, map[string]string{"go.mod": "module example.com/app\n\ngo 1.26.0\n"})

	got := execute(t, dir)
	want := "messages/i18n_gen.go: warning: imports github.com/go-kanna/i18n, which go.mod does not require; " +
		"run go mod tidy\n"
	if got.code != cli.ExitOK || got.err != want {
		t.Errorf("Exec() = %+v, want stderr %q", got, want)
	}
}
